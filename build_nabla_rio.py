#!/usr/bin/env python3
"""
Extract colrv1 payloads for every unique letter in "Rio Terminal
Emulator" from Nabla.ttf and emit them as module constants for the
ratatui (Rust), bubbletea (Go), or ink (TypeScript) demo.

Run from the examples repo root (needs `fonts/Nabla.ttf` on disk):

    python3 build_nabla_rio.py                 # Rust to stdout (default)
    python3 build_nabla_rio.py --lang go       # Go to stdout
    python3 build_nabla_rio.py --lang ts       # TypeScript to stdout
"""

import argparse
import base64
import sys
from pathlib import Path

from extract_colrv1 import extract, load_font

TEXT = "Rio Terminal Emulator"
BASE_CP = 0x100010


def unique_letters_in_order(s: str) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for ch in s:
        if ch == " ":
            continue
        if ch in seen:
            continue
        seen.add(ch)
        out.append(ch)
    return out


def collect_payloads(font_path: Path) -> list[tuple[str, int, str]]:
    letters = unique_letters_in_order(TEXT)
    out: list[tuple[str, int, str]] = []
    for i, ch in enumerate(letters):
        cp = BASE_CP + i
        font = load_font(font_path)
        payload = extract(font, ord(ch))
        b64 = base64.b64encode(payload).decode("ascii")
        sys.stderr.write(
            f"  {ch!r} -> U+{cp:X}  {len(payload)} B raw / {len(b64)} B b64\n"
        )
        out.append((ch, cp, b64))
    return out


def emit_rust(entries: list[tuple[str, int, str]]) -> None:
    print("// Auto-generated by build_nabla_rio.py — do not edit by hand.")
    print("// Payloads are colrv1 containers extracted from Nabla by Arthur")
    print("// Reinders Folmer & Just van Rossum (OFL), subsetted per-letter.")
    print()
    print(f'pub const TEXT: &str = "{TEXT}";')
    print(f"pub const BASE_CP: u32 = 0x{BASE_CP:X};")
    print()
    print("pub const NABLA_LETTERS: &[(char, u32, &str)] = &[")
    for ch, cp, b64 in entries:
        ch_lit = {"'": r"'\''", "\\": r"'\\'"}.get(ch, f"'{ch}'")
        print(f'    ({ch_lit}, 0x{cp:X}, "{b64}"),')
    print("];")


def emit_go(entries: list[tuple[str, int, str]]) -> None:
    print("// Auto-generated by build_nabla_rio.py — do not edit by hand.")
    print("// Payloads are colrv1 containers extracted from Nabla by Arthur")
    print("// Reinders Folmer & Just van Rossum (OFL), subsetted per-letter.")
    print()
    print("package main")
    print()
    print(f'const nablaText = "{TEXT}"')
    print(f"const nablaBaseCp rune = 0x{BASE_CP:X}")
    print()
    print("type nablaEntry struct {")
    print("\tLetter  rune")
    print("\tCp      rune")
    print("\tPayload string")
    print("}")
    print()
    print("var nablaLetters = []nablaEntry{")
    for ch, cp, b64 in entries:
        ch_lit = {"'": r"'\''", "\\": r"'\\'"}.get(ch, f"'{ch}'")
        print(f'\t{{Letter: {ch_lit}, Cp: 0x{cp:X}, Payload: "{b64}"}},')
    print("}")


def emit_ts(entries: list[tuple[str, int, str]]) -> None:
    print("// Auto-generated by build_nabla_rio.py — do not edit by hand.")
    print("// Payloads are colrv1 containers extracted from Nabla by Arthur")
    print("// Reinders Folmer & Just van Rossum (OFL), subsetted per-letter.")
    print()
    print(f"export const nablaText = {json_str(TEXT)};")
    print(f"export const nablaBaseCp = 0x{BASE_CP:X};")
    print()
    print("export interface NablaEntry {")
    print("\tletter: string;")
    print("\tcp: number;")
    print("\tpayload: string;")
    print("}")
    print()
    print("export const nablaLetters: ReadonlyArray<NablaEntry> = [")
    for ch, cp, b64 in entries:
        print(f"\t{{letter: {json_str(ch)}, cp: 0x{cp:X}, payload: {json_str(b64)}}},")
    print("];")


def json_str(s: str) -> str:
    # Double-quoted; escape backslash and double-quote. Base64 and the
    # ASCII-only letters we ship here don't contain anything else worth
    # escaping for TS source.
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--lang", choices=("rust", "go", "ts"), default="rust")
    args = parser.parse_args()

    font_path = Path("fonts/Nabla.ttf")
    if not font_path.exists():
        raise SystemExit(
            "fonts/Nabla.ttf missing. See README for download instructions."
        )
    entries = collect_payloads(font_path)

    {"rust": emit_rust, "go": emit_go, "ts": emit_ts}[args.lang](entries)


if __name__ == "__main__":
    main()
