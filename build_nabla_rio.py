#!/usr/bin/env python3
"""
Extract colrv1 payloads for every unique letter in "Rio Terminal
Emulator" from Nabla.ttf and emit them as module constants for the
ratatui (Rust), bubbletea (Go), or ink (TypeScript) demo.

Run from the examples repo root (needs `fonts/Nabla.ttf` on disk):

    python3 build_nabla_rio.py                 # Rust to stdout (default)
    python3 build_nabla_rio.py --lang go       # Go to stdout
    python3 build_nabla_rio.py --lang ts       # TypeScript to stdout
"""

import argparse
import base64
import sys
from pathlib import Path

from extract_colrv1 import extract, load_font

TEXT = "Rio Terminal Emulator"
BASE_CP = 0x100010

# Shared vertical extent for every letter (spec §8.5.1), filled in by
# main() from the font's hhea table: line height is ascender minus
# descender, ymin is the descender. Each letter also carries its own
# advance as `aw`. With size=height the scale only depends on the
# shared line height, so the letters keep their relative sizes and
# sit on one baseline, and each one is centred by its own advance.
LINE_HEIGHT = 0
YMIN = 0


def read_extent(font_path: Path) -> tuple[int, int]:
    hhea = load_font(font_path)["hhea"]
    return hhea.ascent - hhea.descent, hhea.descent


def unique_letters_in_order(s: str) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for ch in s:
        if ch == " ":
            continue
        if ch in seen:
            continue
        seen.add(ch)
        out.append(ch)
    return out


def collect_payloads(font_path: Path) -> list[tuple[str, int, int, str]]:
    letters = unique_letters_in_order(TEXT)
    out: list[tuple[str, int, int, str]] = []
    for i, ch in enumerate(letters):
        cp = BASE_CP + i
        font = load_font(font_path)
        # Read the advance before extract() subsets the font in place.
        advance = font["hmtx"][font.getBestCmap()[ord(ch)]][0]
        payload = extract(font, ord(ch))
        b64 = base64.b64encode(payload).decode("ascii")
        sys.stderr.write(
            f"  {ch!r} -> U+{cp:X}  {len(payload)} B raw / {len(b64)} B b64\n"
        )
        out.append((ch, cp, advance, b64))
    return out


def emit_rust(entries: list[tuple[str, int, int, str]]) -> None:
    print("// Auto-generated by build_nabla_rio.py — do not edit by hand.")
    print("// Payloads are colrv1 containers extracted from Nabla by Arthur")
    print("// Reinders Folmer & Just van Rossum (OFL), subsetted per-letter.")
    print()
    print(f'pub const TEXT: &str = "{TEXT}";')
    print(f"pub const BASE_CP: u32 = 0x{BASE_CP:X};")
    print(f"pub const LINE_HEIGHT: u32 = {LINE_HEIGHT};")
    print(f"pub const YMIN: i32 = {YMIN};")
    print()
    print("// (letter, codepoint, advance in font units, payload)")
    print("pub const NABLA_LETTERS: &[(char, u32, u32, &str)] = &[")
    for ch, cp, aw, b64 in entries:
        ch_lit = {"'": r"'\''", "\\": r"'\\'"}.get(ch, f"'{ch}'")
        print(f'    ({ch_lit}, 0x{cp:X}, {aw}, "{b64}"),')
    print("];")


def emit_go(entries: list[tuple[str, int, int, str]]) -> None:
    print("// Auto-generated by build_nabla_rio.py — do not edit by hand.")
    print("// Payloads are colrv1 containers extracted from Nabla by Arthur")
    print("// Reinders Folmer & Just van Rossum (OFL), subsetted per-letter.")
    print()
    print("package main")
    print()
    print(f'const nablaText = "{TEXT}"')
    print(f"const nablaBaseCp rune = 0x{BASE_CP:X}")
    print(f"const nablaLineHeight = {LINE_HEIGHT}")
    print(f"const nablaYMin = {YMIN}")
    print()
    print("type nablaEntry struct {")
    print("\tLetter  rune")
    print("\tCp      rune")
    print("\tAdvance int")
    print("\tPayload string")
    print("}")
    print()
    print("var nablaLetters = []nablaEntry{")
    for ch, cp, aw, b64 in entries:
        ch_lit = {"'": r"'\''", "\\": r"'\\'"}.get(ch, f"'{ch}'")
        print(f'\t{{Letter: {ch_lit}, Cp: 0x{cp:X}, Advance: {aw}, Payload: "{b64}"}},')
    print("}")


def emit_ts(entries: list[tuple[str, int, int, str]]) -> None:
    print("// Auto-generated by build_nabla_rio.py — do not edit by hand.")
    print("// Payloads are colrv1 containers extracted from Nabla by Arthur")
    print("// Reinders Folmer & Just van Rossum (OFL), subsetted per-letter.")
    print()
    print(f"export const nablaText = {json_str(TEXT)};")
    print(f"export const nablaBaseCp = 0x{BASE_CP:X};")
    print(f"export const nablaLineHeight = {LINE_HEIGHT};")
    print(f"export const nablaYMin = {YMIN};")
    print()
    print("export interface NablaEntry {")
    print("\tletter: string;")
    print("\tcp: number;")
    print("\tadvance: number;")
    print("\tpayload: string;")
    print("}")
    print()
    print("export const nablaLetters: ReadonlyArray<NablaEntry> = [")
    for ch, cp, aw, b64 in entries:
        print(f"\t{{letter: {json_str(ch)}, cp: 0x{cp:X}, advance: {aw}, payload: {json_str(b64)}}},")
    print("];")


def json_str(s: str) -> str:
    # Double-quoted; escape backslash and double-quote. Base64 and the
    # ASCII-only letters we ship here don't contain anything else worth
    # escaping for TS source.
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--lang", choices=("rust", "go", "ts"), default="rust")
    args = parser.parse_args()

    font_path = Path("fonts/Nabla.ttf")
    if not font_path.exists():
        raise SystemExit(
            "fonts/Nabla.ttf missing. See README for download instructions."
        )
    global LINE_HEIGHT, YMIN
    LINE_HEIGHT, YMIN = read_extent(font_path)
    entries = collect_payloads(font_path)

    {"rust": emit_rust, "go": emit_go, "ts": emit_ts}[args.lang](entries)


if __name__ == "__main__":
    main()
