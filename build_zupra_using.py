#!/usr/bin/env python3
"""
Extract colrv0 payloads for every unique letter in "Using Glyph
protocol" from zupra-3d-eye-fs.colr.ttf and emit them as module
constants for the ratatui (Rust), bubbletea (Go), or ink (TypeScript)
demo.

Run from the examples repo root (needs fonts/zupra-3d-eye-fs.colr.ttf
on disk):

    python3 build_zupra_using.py               # Rust to stdout (default)
    python3 build_zupra_using.py --lang go     # Go to stdout
    python3 build_zupra_using.py --lang ts     # TypeScript to stdout
"""

import argparse
import base64
import sys
from pathlib import Path

from extract_colrv0 import extract, load_font

TEXT = "Using Glyph protocol"
# Sits above Nabla's 0x100010 block so the two colour demos can
# coexist in the same glossary without stomping on each other's slots.
BASE_CP = 0x100030
UPM = 2048

# Shared vertical extent for every letter (spec §8.5.1), filled in by
# main() from the font's hhea table: line height is ascender minus
# descender, ymin is the descender. Each letter also carries its own
# advance as `aw`. With size=height the scale only depends on the
# shared line height, so the letters keep their relative sizes and
# sit on one baseline, and each one is centred by its own advance.
LINE_HEIGHT = 0
YMIN = 0


def read_extent(font_path: Path) -> tuple[int, int]:
    hhea = load_font(font_path)["hhea"]
    return hhea.ascent - hhea.descent, hhea.descent


def unique_letters_in_order(s: str) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for ch in s:
        if ch == " ":
            continue
        if ch in seen:
            continue
        seen.add(ch)
        out.append(ch)
    return out


def collect_payloads(font_path: Path) -> list[tuple[str, int, int, str]]:
    letters = unique_letters_in_order(TEXT)
    out: list[tuple[str, int, int, str]] = []
    for i, ch in enumerate(letters):
        cp = BASE_CP + i
        font = load_font(font_path)
        # Read the advance before extract() subsets the font in place.
        advance = font["hmtx"][font.getBestCmap()[ord(ch)]][0]
        payload = extract(font, ord(ch))
        b64 = base64.b64encode(payload).decode("ascii")
        sys.stderr.write(
            f"  {ch!r} -> U+{cp:X}  {len(payload)} B raw / {len(b64)} B b64\n"
        )
        out.append((ch, cp, advance, b64))
    return out


def emit_rust(entries: list[tuple[str, int, int, str]]) -> None:
    print("// Auto-generated by build_zupra_using.py — do not edit by hand.")
    print("// Payloads are colrv0 containers extracted from zupra 3D eYe/FS")
    print("// by Antonio J. Morata, subsetted per-letter.")
    print()
    print(f'pub const TEXT: &str = "{TEXT}";')
    print(f"pub const BASE_CP: u32 = 0x{BASE_CP:X};")
    print(f"pub const LINE_HEIGHT: u32 = {LINE_HEIGHT};")
    print(f"pub const YMIN: i32 = {YMIN};")
    print(f"pub const UPM: u32 = {UPM};")
    print()
    print("// (letter, codepoint, advance in font units, payload)")
    print("pub const ZUPRA_LETTERS: &[(char, u32, u32, &str)] = &[")
    for ch, cp, aw, b64 in entries:
        ch_lit = {"'": r"'\''", "\\": r"'\\'"}.get(ch, f"'{ch}'")
        print(f'    ({ch_lit}, 0x{cp:X}, {aw}, "{b64}"),')
    print("];")


def emit_go(entries: list[tuple[str, int, int, str]]) -> None:
    print("// Auto-generated by build_zupra_using.py — do not edit by hand.")
    print("// Payloads are colrv0 containers extracted from zupra 3D eYe/FS")
    print("// by Antonio J. Morata, subsetted per-letter.")
    print()
    print("package main")
    print()
    print(f'const zupraText = "{TEXT}"')
    print(f"const zupraBaseCp rune = 0x{BASE_CP:X}")
    print(f"const zupraLineHeight = {LINE_HEIGHT}")
    print(f"const zupraYMin = {YMIN}")
    print(f"const zupraUpm uint32 = {UPM}")
    print()
    print("type zupraEntry struct {")
    print("\tLetter  rune")
    print("\tCp      rune")
    print("\tAdvance int")
    print("\tPayload string")
    print("}")
    print()
    print("var zupraLetters = []zupraEntry{")
    for ch, cp, aw, b64 in entries:
        ch_lit = {"'": r"'\''", "\\": r"'\\'"}.get(ch, f"'{ch}'")
        print(f'\t{{Letter: {ch_lit}, Cp: 0x{cp:X}, Advance: {aw}, Payload: "{b64}"}},')
    print("}")


def emit_ts(entries: list[tuple[str, int, int, str]]) -> None:
    print("// Auto-generated by build_zupra_using.py — do not edit by hand.")
    print("// Payloads are colrv0 containers extracted from zupra 3D eYe/FS")
    print("// by Antonio J. Morata, subsetted per-letter.")
    print()
    print(f"export const zupraText = {json_str(TEXT)};")
    print(f"export const zupraBaseCp = 0x{BASE_CP:X};")
    print(f"export const zupraLineHeight = {LINE_HEIGHT};")
    print(f"export const zupraYMin = {YMIN};")
    print(f"export const zupraUpm = {UPM};")
    print()
    print("export interface ZupraEntry {")
    print("\tletter: string;")
    print("\tcp: number;")
    print("\tadvance: number;")
    print("\tpayload: string;")
    print("}")
    print()
    print("export const zupraLetters: ReadonlyArray<ZupraEntry> = [")
    for ch, cp, aw, b64 in entries:
        print(f"\t{{letter: {json_str(ch)}, cp: 0x{cp:X}, advance: {aw}, payload: {json_str(b64)}}},")
    print("];")


def json_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--lang", choices=("rust", "go", "ts"), default="rust")
    args = parser.parse_args()

    font_path = Path("fonts/zupra-3d-eye-fs.colr.ttf")
    if not font_path.exists():
        raise SystemExit(
            "fonts/zupra-3d-eye-fs.colr.ttf missing. See README for "
            "download instructions."
        )
    global LINE_HEIGHT, YMIN
    LINE_HEIGHT, YMIN = read_extent(font_path)
    entries = collect_payloads(font_path)

    {"rust": emit_rust, "go": emit_go, "ts": emit_ts}[args.lang](entries)


if __name__ == "__main__":
    main()
