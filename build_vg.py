#!/usr/bin/env python3
"""Emit the `fmt=vg` glyphs the ratatui, bubbletea and ink demos register.

    python3 build_vg.py             > ratatui/src/vg.rs
    python3 build_vg.py --lang go   > bubbletea/vg.go
    python3 build_vg.py --lang ts   > ink/source/vg.ts

Sources, all in svg/:
- icons: icon SVGs converted with svg/svg2glyph.py
- paints: the gradient, clip and stroke glyphs drawn by hand in svg/demo.py
- emoji: payloads in svg/emoji/, converted from each set's SVG with
  svg/usvg2vg (see svg/emoji/README.md for their licences)

Standard library only.
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SVG = os.path.join(HERE, "svg")
sys.path.insert(0, SVG)
from svg2glyph import convert  # noqa: E402
import demo  # noqa: E402

FIRST_CP = 0x10_0100  # clear of every other demo registration

ICONS = [
    "lucide/folder.svg", "lucide/git-branch.svg", "lucide/terminal.svg",
    "heroicons/heart.svg", "phosphor/heart-duotone.svg", "tabler/bug.svg",
]
EMOJI = {
    "noto": ["sunglasses", "rocket", "fire", "party"],
    "twemoji": ["grinning", "heart", "pizza", "cat"],
}


def groups():
    """(name, [(vb, extra, payload)]) in print order."""
    icons = [(vb, "", payload)
             for vb, payload in (convert(os.path.join(SVG, "icons", f)) for f in ICONS)]
    paints = [("0,0,24,24", "width=2", p)
              for p in demo.GRADIENTS + demo.CLIPS + [demo.STROKES[1]]]
    out = [("icons", icons), ("paints", paints)]
    for name, files in EMOJI.items():
        emoji = []
        for f in files:
            vb, payload = open(os.path.join(SVG, "emoji", name, f + ".vg")).read().split("\n")[:2]
            emoji.append((vb, "width=2", payload))
        out.append((f"emoji_{name}", emoji))
    return out


def numbered():
    cp = FIRST_CP
    for name, glyphs in groups():
        rows = []
        for vb, extra, payload in glyphs:
            rows.append((cp, vb, extra, payload))
            cp += 1
        yield name, rows


HEADER = (
    "fmt=vg glyphs for the demo, generated by build_vg.py; don't edit.\n"
    "Emoji: Noto Emoji (Google, Apache-2.0 / OFL-1.1) and Twemoji (Twitter\n"
    "and contributors, graphics CC-BY 4.0), converted with svg/usvg2vg.\n"
    "Icons: Lucide (ISC), Heroicons, Phosphor and Tabler (MIT).\n"
)


def rust():
    print("\n".join("// " + l for l in HEADER.splitlines()))
    print()
    print("pub struct VgGlyph {")
    print("    pub cp: u32,")
    print("    pub vb: &'static str,")
    print("    /// Extra keys, e.g. `width=2`; empty for none.")
    print("    pub extra: &'static str,")
    print("    pub payload: &'static str,")
    print("}")
    for name, rows in numbered():
        print()
        print(f"pub const {name.upper()}: &[VgGlyph] = &[")
        for cp, vb, extra, payload in rows:
            print(f"    VgGlyph {{ cp: 0x{cp:x}, vb: {json.dumps(vb)}, extra: {json.dumps(extra)}, payload: {json.dumps(payload)} }},")
        print("];")


def go():
    print("\n".join("// " + l for l in HEADER.splitlines()))
    print()
    print("package main")
    print()
    print("type vgGlyph struct {")
    print("\tcp      uint32")
    print("\tvb      string")
    print("\textra   string // e.g. width=2; empty for none")
    print("\tpayload string")
    print("}")
    for name, rows in numbered():
        ident = "vg" + "".join(p.capitalize() for p in name.split("_"))
        print()
        print(f"var {ident} = []vgGlyph{{")
        for cp, vb, extra, payload in rows:
            print(f"\t{{0x{cp:x}, {json.dumps(vb)}, {json.dumps(extra)}, `{payload}`}},")
        print("}")


def ts():
    print("\n".join("// " + l for l in HEADER.splitlines()))
    print()
    print("export type VgGlyph = {")
    print("\tcp: number;")
    print("\tvb: string;")
    print("\t/** Extra keys, e.g. `width=2`; empty for none. */")
    print("\textra: string;")
    print("\tpayload: string;")
    print("};")
    for name, rows in numbered():
        ident = "VG_" + name.upper()
        print()
        print(f"export const {ident}: readonly VgGlyph[] = [")
        for cp, vb, extra, payload in rows:
            print(f"\t{{cp: 0x{cp:x}, vb: {json.dumps(vb)}, extra: {json.dumps(extra)}, payload: {json.dumps(payload)}}},")
        print("];")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--lang", choices=("rust", "go", "ts"), default="rust")
    args = ap.parse_args()
    {"rust": rust, "go": go, "ts": ts}[args.lang]()


if __name__ == "__main__":
    main()
